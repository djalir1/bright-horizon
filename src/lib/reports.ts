import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import logoImage from '@/assets/senior-gala-logo.png';
import { formatDate, formatDateTimeSec } from '@/lib/format';

// === Brand palette (matches src/lib/pdf.ts) ===
const COL_BG: [number, number, number] = [6, 6, 15];
const COL_GOLD: [number, number, number] = [201, 168, 76];
const COL_TEXT: [number, number, number] = [245, 240, 232];
const COL_MUTED: [number, number, number] = [138, 128, 112];

async function loadLogoDataUrl(): Promise<string | null> {
  try {
    const res = await fetch(logoImage);
    const blob = await res.blob();
    return await new Promise<string>((resolve, reject) => {
      const r = new FileReader();
      r.onloadend = () => resolve(r.result as string);
      r.onerror = reject;
      r.readAsDataURL(blob);
    });
  } catch { return null; }
}

function safe(v: any): string {
  if (v === null || v === undefined) return '-';
  return String(v);
}

/** Download arbitrary rows as a CSV file. */
export function exportCsv(filename: string, headers: string[], rows: (string | number | null | undefined)[][]) {
  const escape = (v: any) => {
    const s = v === null || v === undefined ? '' : String(v);
    if (/[",\n]/.test(s)) return `"${s.replace(/"/g, '""')}"`;
    return s;
  };
  const csv = [headers.map(escape).join(','), ...rows.map(r => r.map(escape).join(','))].join('\n');
  const blob = new Blob(['\uFEFF' + csv], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

export interface ReportOptions {
  title: string;
  subtitle?: string;
  headers: string[];
  rows: (string | number | null | undefined)[][];
  filename: string;
  /** Optional column widths in mm (totals roughly to page width minus margins). */
  columnStyles?: Record<number, { cellWidth?: number; halign?: 'left' | 'center' | 'right' }>;
}

/** Brand-themed landscape PDF with logo, title, table, footer. */
export async function exportPdfReport(opts: ReportOptions): Promise<void> {
  const doc = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a4' });
  const w = doc.internal.pageSize.getWidth();
  const h = doc.internal.pageSize.getHeight();

  // background
  doc.setFillColor(...COL_BG);
  doc.rect(0, 0, w, h, 'F');

  // top gold bar
  doc.setFillColor(...COL_GOLD);
  doc.rect(0, 0, w, 2, 'F');

  // Logo
  const logo = await loadLogoDataUrl();
  if (logo) {
    try { doc.addImage(logo, 'PNG', 10, 6, 18, 18); } catch {}
  }

  // Title
  doc.setFont('times', 'bold');
  doc.setFontSize(18);
  doc.setTextColor(...COL_GOLD);
  doc.text(opts.title, 32, 15);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(...COL_MUTED);
  doc.text(opts.subtitle || `Generated ${formatDate(new Date().toISOString())}`, 32, 21);

  // Right-aligned brand mark
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(...COL_GOLD);
  doc.text('SENIOR GALA KIGALI 2026', w - 10, 12, { align: 'right' });
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7);
  doc.setTextColor(...COL_MUTED);
  doc.text('seniorgalakigali.sadcorporation.com', w - 10, 17, { align: 'right' });

  // Table
  autoTable(doc, {
    head: [opts.headers],
    body: opts.rows.map(r => r.map(safe)),
    startY: 30,
    margin: { left: 10, right: 10, bottom: 18 },
    theme: 'grid',
    styles: {
      font: 'helvetica',
      fontSize: 8,
      textColor: COL_TEXT,
      fillColor: [15, 15, 26],
      lineColor: [40, 35, 22],
      lineWidth: 0.1,
      cellPadding: 2,
    },
    headStyles: {
      fillColor: COL_GOLD,
      textColor: COL_BG,
      fontStyle: 'bold',
      halign: 'left',
    },
    alternateRowStyles: { fillColor: [20, 20, 32] },
    columnStyles: opts.columnStyles,
    didDrawPage: () => {
      const pageHeight = doc.internal.pageSize.getHeight();
      const pageWidth = doc.internal.pageSize.getWidth();
      // Footer band
      doc.setFillColor(...COL_GOLD);
      doc.rect(0, pageHeight - 10, pageWidth, 10, 'F');
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(8);
      doc.setTextColor(...COL_BG);
      doc.text('Generated by S.A.D Corporation', 10, pageHeight - 3.5);
      const page = (doc as any).internal.getCurrentPageInfo().pageNumber;
      doc.text(`Page ${page}`, pageWidth - 10, pageHeight - 3.5, { align: 'right' });
      doc.text('seniorgalakigali.sadcorporation.com  ·  Senior Gala Kigali 2026', pageWidth / 2, pageHeight - 3.5, { align: 'center' });
    },
  });

  doc.save(opts.filename);
}

/** Single-student payment report — used from AdminPayments per-row print. */
export async function exportStudentPaymentPdf(student: {
  code: string;
  name: string;
  school: string;
  level?: string;
  phone?: string;
  email?: string;
  ticket_price: number;
  paid_amount: number;
  remaining_amount: number;
  payment_status: string;
  entered?: boolean;
  entered_at?: string | null;
  exited?: boolean;
  exited_at?: string | null;
}, payments: Array<{
  amount: number; method: string; status: string; submitted_at: string;
  reviewed_by?: string | null; transaction_id?: string | null;
}>) {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  const w = doc.internal.pageSize.getWidth();
  const h = doc.internal.pageSize.getHeight();

  doc.setFillColor(...COL_BG); doc.rect(0, 0, w, h, 'F');
  doc.setFillColor(...COL_GOLD); doc.rect(0, 0, w, 2, 'F');

  const logo = await loadLogoDataUrl();
  if (logo) { try { doc.addImage(logo, 'PNG', 12, 8, 22, 22); } catch {} }

  doc.setFont('times', 'bold'); doc.setFontSize(20); doc.setTextColor(...COL_GOLD);
  doc.text('Student Payment Report', 40, 18);
  doc.setFont('helvetica', 'normal'); doc.setFontSize(9); doc.setTextColor(...COL_MUTED);
  doc.text(`Generated ${formatDate(new Date().toISOString())}`, 40, 24);

  doc.setFont('helvetica', 'bold'); doc.setFontSize(9); doc.setTextColor(...COL_GOLD);
  doc.text('SENIOR GALA KIGALI 2026', w - 12, 14, { align: 'right' });
  doc.setFont('helvetica', 'normal'); doc.setFontSize(7); doc.setTextColor(...COL_MUTED);
  doc.text('seniorgalakigali.sadcorporation.com', w - 12, 19, { align: 'right' });

  // Student info box
  doc.setDrawColor(...COL_GOLD); doc.setLineWidth(0.3);
  doc.setFillColor(15, 15, 26);
  doc.roundedRect(12, 36, w - 24, 56, 2, 2, 'FD');

  const rows: [string, string][] = [
    ['Code', student.code],
    ['Name', student.name],
    ['School', student.school],
    ['Level', student.level || '-'],
    ['Phone', student.phone || '-'],
    ['Email', student.email || '-'],
    ['Ticket Price', `${student.ticket_price.toLocaleString()} RWF`],
    ['Paid', `${student.paid_amount.toLocaleString()} RWF`],
    ['Remaining', `${student.remaining_amount.toLocaleString()} RWF`],
    ['Status', student.payment_status.toUpperCase()],
    ['Entry', student.entered ? `Entered ${student.entered_at ? formatDateTimeSec(student.entered_at) : ''}` : 'Not entered'],
    ['Exit', student.exited ? `Exited ${student.exited_at ? formatDateTimeSec(student.exited_at) : ''}` : '-'],
  ];

  let y = 43;
  doc.setFontSize(9);
  rows.forEach(([k, v], i) => {
    const col = i % 2;
    const row = Math.floor(i / 2);
    const x = 18 + col * ((w - 24) / 2);
    const yy = 43 + row * 8;
    doc.setFont('helvetica', 'normal'); doc.setTextColor(...COL_MUTED);
    doc.text(k, x, yy);
    doc.setFont('helvetica', 'bold'); doc.setTextColor(...COL_TEXT);
    doc.text(v, x + 28, yy);
  });

  // Payments table
  autoTable(doc, {
    head: [['Date', 'Amount', 'Method', 'Status', 'Reviewed by', 'TXN ID']],
    body: payments.map(p => [
      formatDateTimeSec(p.submitted_at),
      `${p.amount.toLocaleString()} RWF`,
      p.method.toUpperCase(),
      p.status.toUpperCase(),
      p.reviewed_by || '-',
      p.transaction_id || '-',
    ]),
    startY: 100,
    margin: { left: 12, right: 12, bottom: 18 },
    theme: 'grid',
    styles: { font: 'helvetica', fontSize: 8, textColor: COL_TEXT, fillColor: [15, 15, 26], lineColor: [40, 35, 22], lineWidth: 0.1, cellPadding: 2 },
    headStyles: { fillColor: COL_GOLD, textColor: COL_BG, fontStyle: 'bold' },
    alternateRowStyles: { fillColor: [20, 20, 32] },
    didDrawPage: () => {
      const ph = doc.internal.pageSize.getHeight();
      const pw = doc.internal.pageSize.getWidth();
      doc.setFillColor(...COL_GOLD); doc.rect(0, ph - 10, pw, 10, 'F');
      doc.setFont('helvetica', 'bold'); doc.setFontSize(8); doc.setTextColor(...COL_BG);
      doc.text('Generated by S.A.D Corporation', 10, ph - 3.5);
      doc.text(student.code, pw - 10, ph - 3.5, { align: 'right' });
      doc.text('seniorgalakigali.sadcorporation.com', pw / 2, ph - 3.5, { align: 'center' });
    },
  });

  doc.save(`Senior-Gala-Payment-${student.code}.pdf`);
}